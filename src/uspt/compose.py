def generate_xcompose_content(date_str: str = "") -> str:
    """Gera o conteúdo do ficheiro XCompose com mapeamentos portugueses."""
    date_part = date_str or __import__("datetime").datetime.now().strftime("%Y-%m-%d")
    content = XCOMPOSE_TEMPLATE.format(date=date_part)
    return content


def write_xcompose_file(path: str = DEFAULT_XCOMPOSE_PATH, date_str: str = "") -> Dict[str, Any]:
    """Escreve o ficheiro XCompose com mapeamentos portugueses.

    Creates backup of existing file if present.

    Returns dicionário com status e detalhes.
    """
    result = {
        "success": False,
        "path": path,
        "file_written": False,
        "backup_created": False,
        "warnings": [],
    }

    # Step 1: Backup existing if present
    if os.path.exists(path):
        backup_path = path + ".backup." + __import__("datetime").datetime.now().strftime("%Y%m%d%H%M%S")
        try:
            with open(path, "r") as original:
                content = original.read()
            with open(backup_path, "w") as backup:
                backup.write(content)
            result["backup_created"] = True
            result["warnings"].append(
                "Ficheiro XCompose existente fez backup em: " + backup_path
            )
        except IOError as e:
            result["warnings"].append(
                "Não foi possível fazer backup do ficheiro existente: " + str(e)
            )

    # Step 2: Write new content
    try:
        content = generate_xcompose_content(date_str)
        os.makedirs(os.path.dirname(path), exist_ok=True) if os.path.dirname(path) else None
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        result["file_written"] = True
        result["success"] = True
        logger.info("XCompose file written to: %s", path)
    except IOError as e:
        result["warnings"].append("Não foi possível escrever ficheiro XCompose: " + str(e))

    return result


def remove_xcompose_file(path: str = DEFAULT_XCOMPOSE_PATH) -> Dict[str, Any]:
    """Remove o ficheiro XCompose (restauração)."""
    result = {
        "success": False,
        "path": path,
        "file_removed": False,
        "restored_from_backup": False,
    }

    if os.path.exists(path):
        # Try to restore from backup first
        backup_path = path + ".backup."
        import glob
        backups = glob.glob(path + ".backup.*")
        if backups:
            # Use the most recent backup
            backups.sort()
            latest_backup = backups[-1]
            try:
                with open(latest_backup, "r") as b:
                    content = b.read()
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
                result["restored_from_backup"] = True
                result["success"] = True
            except IOError as e:
                result["warnings"].append("Não foi possível restaurar backup: " + str(e))
        else:
            # No backup, just remove
            try:
                os.remove(path)
                result["file_removed"] = True
                result["success"] = True
            except OSError as e:
                result["warnings"].append("Não foi possível remover ficheiro: " + str(e))

    else:
        result["success"] = True  # Nothing to remove

    return result


