def detect_compose_key() -> Dict[str, Any]:
    """Deteta se existe uma tecla compose configurada ou disponível.

    Returns informação sobre a tecla compose.
    """
    result = {
        "compose_key_available": False,
        "compose_key": None,
        "xkb_options_with_compose": [],
    }

    # Check if compose:ralt or similar is in xkb options
    try:
        result_sub = __import__("subprocess").run(
            ["setxkbmap", "-query"],
            capture_output=True, text=True,
            timeout=5,
        )
        if result_sub.returncode == 0:
            for line in result_sub.stdout.splitlines():
                if "options:" in line.lower():
                    result["xkb_options_with_compose"] = [
                        o.strip() for o in line.split(":", 1)[1].strip().split(",")
                    ]
    except FileNotFoundError:
        pass

    # Check environment variables
    if __import__("os").environ.get("QT_IM_MODULE", ""):
        pass  # IME mode

    return result