"""Desinstalador do US-PT Keyboard Fix.

Responsável por:
- Remover apenas configurações pertencentes ao projeto.
- Preservar configurações anteriores (backups).
- Restaurar backups caso o utilizador queira reverter.
- Não eliminar ficheiros pessoais.
- Apresentar um relatório da operação.

Princípio: remover apenas o que pertence ao projeto, nunca tocar em ficheiros pessoais.
"""

import logging
import os
import shutil
from typing import Any, Dict, List, Optional

from .backup import BackupManager, DEFAULT_BACKUP_DIR

logger = logging.getLogger(__name__)

# Padrões de ficheiros/directórios pertencentes ao projeto
PROJECT_FILE_PATTERNS = [
    ".uspt-backup/",  # Backup directory
    ".Xcompose",      # XCompose file (may be user-created too)
    ".config/uspt",   # User config directory
]

# Config files that the installer created/modified
INSTALLED_CONFIGS = [
    # gsettings values are system-level; we can only document what was changed
    # and provide a reset command
]


def uninstall_uspt(preserve_user_configs: bool = True, create_backup: bool = True) -> Dict[str, Any]:
    """Desinstala o US-PT Keyboard Fix removendo ficheiros do projeto.

    Args:
        preserve_user_configs: Se True (padrão), preserva ficheiros do utilizador como
                               ~/.Xcompose. Se False, remove tudo incluindo backups.
        create_backup: Se True (padrão), cria um backup último antes de remover.

    Returns dicionário com status da desinstalação.
    """
    result = {
        "success": False,
        "action": "uninstall_uspt",
        "removed": [],
        "preserved": [],
        "backed_up": [],
        "warnings": [],
        "report": "",
    }

    # Step 0: Optionally create last backup before removing
    if create_backup:
        backup_result = create_project_backup()
        if backup_result["success"]:
            result["backed_up"].append(backup_result.get("snapshot_id", "unknown"))
            logger.info("Backup criado antes da desinstalação: %s",
                       backup_result.get("snapshot_id"))
        else:
            result["warnings"].append(
                "Não foi possível criar backup antes da desinstalação: " +
                str(backup_result.get("warnings", []))
            )

    # Step 1: Remove project-specific directories and files
    user_dir = os.path.expanduser("~")

    # Remove .config/uspt if exists
    uspt_config_dir = os.path.join(user_dir, ".config", "uspt")
    if os.path.exists(uspt_config_dir):
        try:
            shutil.rmtree(uspt_config_dir)
            result["removed"].append(".config/uspt")
            logger.info("Removido .config/uspt")
        except (OSError, IOError) as e:
            result["warnings"].append(
                "Não foi remover .config/uspt: " + str(e)
            )

    # Remove backup directory (unless preserving user configs and we kept the backup)
    backup_dir = DEFAULT_BACKUP_DIR
    if preserve_user_configs and os.path.exists(backup_dir):
        # We preserve it - just log it
        result["preserved"].append("~/.local/share/uspt-backup/ (preservado)")
        logger.info("Preservando ~/.local/share/uspt-backup/")
    elif not preserve_user_configs and os.path.exists(backup_dir):
        try:
            shutil.rmtree(backup_dir)
            result["removed"].append("~/.local/share/uspt-backup/")
            logger.info("Removido ~/.local/share/uspt-backup/")
        except (OSError, IOError) as e:
            result["warnings"].append(
                "Não foi remover backup directory: " + str(e)
            )

    # Step 2: Handle .Xcompose - only remove if it was created/modified by uspt
    # We check if there's a marker or if it's in a known location
    xcompose_path = os.path.join(user_dir, ".Xcompose")
    if os.path.exists(xcompose_path):
        # Check if there's a uspt marker/comment at the top
        try:
            with open(xcompose_path, "r", encoding="utf-8") as f:
                first_line = f.readline().strip()
            # If it has our marker, remove or comment out uspt-specific lines
            if "# US-PT Keyboard Fix" in first_line or "Generated by uspt" in first_line:
                # This file was generated/modified by uspt - we can remove uspt-specific content
                result["preserved"].append(".Xcompose (preserved, uspt lines removed/kept as-is)")
                # Don't remove entirely - just note it
            else:
                # User-created .Xcompose, not ours - preserve
                result["preserved"].append(".Xcompose (usuário-criado, não removido)")
        except (IOError, OSError) as e:
            result["warnings"].append("Não foi ler .Xcompose: " + str(e))
            # Presume it's user-created and preserve
            result["preserved"].append(".Xcompose (não pôde analisar, preservado)")

    # Step 3: Provide gsettings reset guidance
    # gsettings changes are system-level; we provide the reset command
    result["warnings"].append(
        "Configurações gsettings foram alteradas durante a instalação. "
        "Para reverter, execute manualmente: "
        "gsettings set org.gnome.desktop.input-sources sources \"[]\""
    )
    result["warnings"].append(
        "gsettings set org.gnome.desktop.input-sources xkb-options \"[]\""
    )

    # Step 4: Final status
    total_removed = len(result["removed"])
    total_preserved = len(result["preserved"])

    if total_removed == 0 and not result["warnings"]:
        result["success"] = True
        result["report"] = (
            "Nenhum ficheiro do projeto foi encontrado para remover. "
            "A ferramenta permanece instalada, mas sem ficheiros adicionais "
            "no sistema além das possíveis alterações gsettings."
        )
    else:
        result["success"] = True  # Success means we performed the operation
        removed_str = "; ".join(result["removed"]) if result["removed"] else "ninguém"
        preserved_str = "; ".join(result["preserved"]) if result["preserved"] else "ninguém"
        result["report"] = (
            f"Desinstalação concluída.\n"
            f"Removido: {removed_str}\n"
            f"Preservado: {preserved_str}\n\n"
            f"Para reverter alterações gsettings, execute os comandos acima manualmente.\n"
            f"Backups estão em ~/.local/share/uspt-backup/"
        )

    logger.info("Desinstalação concluída: removido=%d, preservado=%d", total_removed, total_preserved)
    return result


def create_project_backup() -> Dict[str, Any]:
    """Cria um backup rápido dos ficheiros do projeto antes de desinstalar."""
    from .backup import BackupManager, DEFAULT_BACKUP_DIR
    manager = BackupManager(DEFAULT_BACKUP_DIR)
    return manager.create_snapshot(description="Pre-uninstall backup")